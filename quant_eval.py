"""
quant_eval.py — personal mixed precision: does knowing a user's experts buy quality?

Experiment 5 showed that each user's expert usage is stable and specific, but that a
static personal core does not beat an LRU cache. A cache can adapt; precision cannot
(you quantize once, offline). So here we test the signal where it cannot be replaced:

    hi experts   kept at --hi-bits (default 8)
    lo experts   quantized to --lo-bits (default 3)

For every user, the hi experts per layer are chosen by four rules, all with the same
memory: personal (user's own first 70% of prompts), population (all OTHER users),
random, oracle (the user's test prompts themselves, upper bound). Baselines: every
expert at --uniform-bits (default 4) and every expert at hi / lo bits.

Quality = KL(full model || quantized model) per token on the user's LATER prompts plus
a greedy reply of --gen-tokens generated by the full fp16 model, and top-1 agreement.
Chat-template tokens are skipped. Quantization: round-to-nearest, asymmetric, groups of
--group along the input dimension (scale + zero in fp16 -> +32/group bits per weight).

The model is built straight from the checkpoint's safetensors: the full fp16 model sits
on the GPU once (reference), then only the quantized codes + the current hi experts.
OLMoE-1B-7B on a T4 (15 GB): ~13 GB in phase 1, ~8 GB after.

    python quant_eval.py --model allenai/OLMoE-1B-7B-0125-Instruct \\
        --prompts prompts/wildchat_users.jsonl --counts results_users/all.npz --outdir results_quant
"""

import argparse
import glob
import json
import os
import re
import time
import zlib
from collections import defaultdict

import numpy as np
import torch
from torch import nn

EXPERT_RE = re.compile(r"^(.*\.experts)\.(\d+)\.(gate_proj|up_proj|down_proj)\.weight$")
FUSED_RE = re.compile(r"^(.*\.experts)\.(gate_up_proj|down_proj)$")


# ---------------------------------------------------------------- quantization

def quantize(w, bits, group):
    """w [..., n] float -> (codes uint8, scale fp16, zero fp16). Packs 2 codes/byte when bits <= 4."""
    shape = w.shape
    g = w.float().reshape(*shape[:-1], shape[-1] // group, group)
    mn, mx = g.amin(-1, keepdim=True), g.amax(-1, keepdim=True)
    qmax = 2 ** bits - 1
    scale = ((mx - mn) / qmax).clamp_min(1e-8)
    q = ((g - mn) / scale).round_().clamp_(0, qmax).to(torch.uint8).reshape(shape)
    if bits <= 4:
        q = q[..., 0::2] | (q[..., 1::2] << 4)
    return q, scale.squeeze(-1).half(), mn.squeeze(-1).half()


def dequantize(q, scale, zero, bits, group, dtype=torch.float16):
    if bits <= 4:
        q = torch.stack((q & 15, q >> 4), dim=-1).reshape(*q.shape[:-1], q.shape[-1] * 2)
    shape = q.shape
    g = q.reshape(*shape[:-1], shape[-1] // group, group).to(dtype)
    return (g * scale.unsqueeze(-1).to(dtype) + zero.unsqueeze(-1).to(dtype)).reshape(shape)


def fake_quant(w, bits, group):
    if bits >= 16:
        return w
    return dequantize(*quantize(w, bits, group), bits, group, w.dtype)


class LoSet:
    """Quantized codes of every expert at one bit width (per layer, stacked over experts)."""

    def __init__(self, L, bits, group):
        self.bits, self.group = bits, group
        self.gu = [None] * L
        self.dn = [None] * L
        self.device = "cpu"

    def put(self, layer, e, E, gu, dn):
        if self.gu[layer] is None:
            self.gu[layer] = [None] * E
            self.dn[layer] = [None] * E
        self.gu[layer][e] = tuple(t.cpu() for t in quantize(gu, self.bits, self.group))
        self.dn[layer][e] = tuple(t.cpu() for t in quantize(dn, self.bits, self.group))

    def finalize(self):
        """Stack per-expert codes into per-layer tensors."""
        for store in (self.gu, self.dn):
            for l, items in enumerate(store):
                store[l] = tuple(torch.stack([it[i] for it in items]) for i in range(3))

    def to(self, device):
        for store in (self.gu, self.dn):
            for l, t in enumerate(store):
                store[l] = tuple(x.to(device) for x in t)
        self.device = device
        return self

    def weights(self, layer, e):
        return (dequantize(*(x[e] for x in self.gu[layer]), self.bits, self.group),
                dequantize(*(x[e] for x in self.dn[layer]), self.bits, self.group))

    def nbytes(self):
        return sum(x.numel() * x.element_size() for s in (self.gu, self.dn) for t in s for x in t)


# ---------------------------------------------------------------- model

class Bank:
    """Where each expert's weights come from: hi dict (fp16 on GPU) or the active lo set."""

    def __init__(self, L, E):
        self.L, self.E = L, E
        self.hi = {}
        self.lo = None
        self.fake_bits, self.group = None, 64      # quantize hi weights on the fly (phase 1 baselines)
        self.usage = np.zeros((L, E), dtype=np.int64)

    def weights(self, layer, e):
        w = self.hi.get((layer, e))
        if w is not None:
            if self.fake_bits:
                return fake_quant(w[0], self.fake_bits, self.group), fake_quant(w[1], self.fake_bits, self.group)
            return w
        return self.lo.weights(layer, e)


class BankExperts(nn.Module):
    def __init__(self, bank, layer, act_fn, num_experts):
        super().__init__()
        self.bank, self.layer, self.act_fn, self.num_experts = bank, layer, act_fn, num_experts

    def forward(self, hidden_states, top_k_index, top_k_weights):
        out = torch.zeros_like(hidden_states)
        counts = torch.bincount(top_k_index.reshape(-1), minlength=self.num_experts)[: self.num_experts]
        counts = counts.cpu().numpy()
        self.bank.usage[self.layer] += counts
        for e in np.nonzero(counts)[0]:
            token_idx, pos = torch.where(top_k_index == int(e))
            gate_up, down = self.bank.weights(self.layer, int(e))
            x = hidden_states[token_idx]
            gate, up = nn.functional.linear(x, gate_up.to(x.dtype)).chunk(2, dim=-1)
            h = nn.functional.linear(self.act_fn(gate) * up, down.to(x.dtype))
            h = h * top_k_weights[token_idx, pos, None]
            out.index_add_(0, token_idx, h.to(out.dtype))
        return out


class Checkpoint:
    """Random access to expert weights in the original safetensors files."""

    def __init__(self, path):
        from safetensors import safe_open
        files = sorted(glob.glob(os.path.join(path, "*.safetensors")))
        if not files:
            raise SystemExit(f"no .safetensors files in {path}")
        self.handles = [safe_open(f, framework="pt", device="cpu") for f in files]
        self.where = {}
        for h in self.handles:
            for k in h.keys():
                self.where[k] = h
        self.experts = {}        # (prefix, e) -> {gate, up, down: key}   or prefix -> fused keys
        self.fused = {}
        self.other = []
        for k in self.where:
            m = EXPERT_RE.match(k)
            if m:
                self.experts.setdefault((m.group(1), int(m.group(2))), {})[m.group(3)] = k
                continue
            m = FUSED_RE.match(k)
            if m:
                self.fused.setdefault(m.group(1), {})[m.group(2)] = k
                continue
            self.other.append(k)

    def get(self, key):
        return self.where[key].get_tensor(key)

    def expert(self, prefix, e):
        """(gate_up [2I, H], down [H, I]) in the transformers >= 5 layout."""
        if prefix in self.fused:
            f = self.fused[prefix]
            return (self.where[f["gate_up_proj"]].get_slice(f["gate_up_proj"])[e],
                    self.where[f["down_proj"]].get_slice(f["down_proj"])[e])
        k = self.experts[(prefix, e)]
        return torch.cat([self.get(k["gate_proj"]), self.get(k["up_proj"])], dim=0), self.get(k["down_proj"])


def resolve(model_id):
    if os.path.isdir(model_id):
        return model_id
    from huggingface_hub import snapshot_download
    return snapshot_download(model_id, allow_patterns=["*.json", "*.safetensors", "*.model", "*.txt", "tokenizer*"])


def build(path, device, dtype):
    from accelerate import init_empty_weights
    from transformers import AutoConfig, AutoModelForCausalLM, AutoTokenizer

    config = AutoConfig.from_pretrained(path)
    with init_empty_weights():
        model = AutoModelForCausalLM.from_config(config)
    ck = Checkpoint(path)

    expert_modules = []
    for name, m in model.named_modules():
        if isinstance(getattr(m, "gate_up_proj", None), nn.Parameter) and \
                isinstance(getattr(m, "down_proj", None), nn.Parameter):
            expert_modules.append((name, m))
    if not expert_modules:
        raise SystemExit("no expert modules found (needs transformers >= 5 and an MoE model)")
    L, E = len(expert_modules), expert_modules[0][1].gate_up_proj.shape[0]
    bank = Bank(L, E)
    prefixes = []
    for i, (name, m) in enumerate(expert_modules):
        parent_name, _, attr = name.rpartition(".")
        setattr(model.get_submodule(parent_name), attr, BankExperts(bank, i, m.act_fn, E))
        prefixes.append(name)
    missing_prefix = [p for p in prefixes if p not in ck.fused and (p, 0) not in ck.experts]
    if missing_prefix:
        raise SystemExit(f"checkpoint has no experts for {missing_prefix[:2]}")

    state = {k: ck.get(k) for k in ck.other}
    state = {k: (v.to(dtype) if v.is_floating_point() else v) for k, v in state.items()}
    _, unexpected = model.load_state_dict(state, strict=False, assign=True)
    model.tie_weights()
    still_meta = [n for n, p in model.named_parameters() if p.is_meta]
    if still_meta or unexpected:
        raise SystemExit(f"checkpoint does not match model: missing={still_meta[:3]} unexpected={unexpected[:3]}")
    model.to(device).eval()
    for p in model.parameters():
        p.requires_grad_(False)
    tok = AutoTokenizer.from_pretrained(path)
    return model, tok, bank, ck, prefixes


# ---------------------------------------------------------------- data

def load_prompts(path):
    rows = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            if line.strip():
                o = json.loads(line)
                t = (o.get("text") or o.get("prompt") or "").strip()
                if t:
                    rows.append((o.get("user", "u?"), t))
    return rows


def template_prefix_len(tok, text):
    a = tok.apply_chat_template([{"role": "user", "content": text}], add_generation_prompt=True,
                                return_tensors="pt", return_dict=True)["input_ids"][0].tolist()
    b = tok.apply_chat_template([{"role": "user", "content": "x" + text}], add_generation_prompt=True,
                                return_tensors="pt", return_dict=True)["input_ids"][0].tolist()
    n = 0
    while n < min(len(a), len(b)) and a[n] == b[n]:
        n += 1
    return n


def greedy(model, ids, n, eos_id):
    """Greedy decoding with an explicit KV cache (model.generate can silently skip the cache here)."""
    if n <= 0:
        return ids
    out = model(ids, use_cache=True)
    past, nxt = out.past_key_values, out.logits[:, -1].argmax(-1, keepdim=True)
    toks = [nxt]
    for _ in range(n - 1):
        if eos_id is not None and int(nxt) == eos_id:
            break
        out = model(nxt, past_key_values=past, use_cache=True)
        past, nxt = out.past_key_values, out.logits[:, -1].argmax(-1, keepdim=True)
        toks.append(nxt)
    return torch.cat([ids] + toks, dim=1)


def kl_metrics(logits, ref):
    """Coarse-grained KL(P_ref || Q) over P's top-k + one tail bucket, and top-1 agreement."""
    logq = torch.log_softmax(logits.float(), dim=-1)
    idx, logp = ref["idx"].to(logits.device).long(), ref["logp"].to(logits.device).float()
    p = logp.exp()
    q_top = logq.gather(-1, idx)
    p_tail = (1 - p.sum(-1)).clamp_min(1e-9)
    q_tail = (1 - q_top.exp().sum(-1)).clamp_min(1e-9)
    kl = (p * (logp - q_top)).sum(-1) + p_tail * (p_tail.log() - q_tail.log())
    agree = (logq.argmax(-1) == idx[:, 0]).float()
    return kl.clamp_min(0).cpu().numpy(), agree.cpu().numpy()


# ---------------------------------------------------------------- main

def ram_gb():
    try:
        import psutil
        return psutil.Process().memory_info().rss / 1e9
    except Exception:
        return float("nan")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--model", required=True)
    ap.add_argument("--prompts", required=True)
    ap.add_argument("--counts", required=True, help="per-prompt expert counts from profile_experts.py")
    ap.add_argument("--train-frac", type=float, default=0.7)
    ap.add_argument("--budgets", default="0.125,0.25", help="share of experts per layer kept at hi bits")
    ap.add_argument("--hi-bits", type=int, default=8)
    ap.add_argument("--lo-bits", type=int, default=3)
    ap.add_argument("--uniform-bits", default="4", help="comma list of uniform baselines")
    ap.add_argument("--group", type=int, default=64)
    ap.add_argument("--rules", default="personal,oracle,population,random")
    ap.add_argument("--gen-tokens", type=int, default=32)
    ap.add_argument("--max-prompt-tokens", type=int, default=256)
    ap.add_argument("--ref-topk", type=int, default=64)
    ap.add_argument("--users", type=int, default=0, help="only the first N users (0 = all)")
    ap.add_argument("--device", default="auto")
    ap.add_argument("--dtype", default="auto", choices=["auto", "float16", "float32", "bfloat16"])
    ap.add_argument("--outdir", default="results_quant")
    args = ap.parse_args()

    device = ("cuda" if torch.cuda.is_available() else "cpu") if args.device == "auto" else args.device
    dtype = (torch.float16 if device == "cuda" else torch.float32) if args.dtype == "auto" else getattr(torch, args.dtype)
    os.makedirs(args.outdir, exist_ok=True)
    budgets = [float(b) for b in args.budgets.split(",")]
    uniform_bits = [int(b) for b in args.uniform_bits.split(",") if b]
    rules = [r for r in args.rules.split(",") if r]
    t_start = time.time()

    # --- users and their expert statistics (same split as analyze_users.py)
    rows = load_prompts(args.prompts)
    counts = np.load(args.counts)["counts"].astype(np.float64)
    if len(rows) != counts.shape[0]:
        raise SystemExit(f"prompts ({len(rows)}) and counts ({counts.shape[0]}) do not line up")
    by_user = defaultdict(list)
    for i, (u, _) in enumerate(rows):
        by_user[u].append(i)
    names = sorted(by_user)
    split = {}
    for u in names:
        idx = by_user[u]
        n_train = max(1, min(len(idx) - 1, int(round(len(idx) * args.train_frac))))
        split[u] = (idx[:n_train], idx[n_train:])
    train_sum = {u: counts[split[u][0]].sum(0) for u in names}
    test_sum = {u: counts[split[u][1]].sum(0) for u in names}
    train_norm = {u: train_sum[u] / max(train_sum[u].sum(), 1) for u in names}
    all_norm = sum(train_norm.values())
    if args.users:
        names = names[: args.users]

    # --- phase 1: full model on the device, reference outputs, quantized codes
    path = resolve(args.model)
    print(f"[load] {path}", flush=True)
    model, tok, bank, ck, prefixes = build(path, device, dtype)
    L, E = bank.L, bank.E
    if counts.shape[1:] != (L, E):
        raise SystemExit(f"counts are {counts.shape[1:]} but the model has {L} x {E} experts")
    los = {args.lo_bits: LoSet(L, args.lo_bits, args.group)}     # only the lo set is kept as codes (CPU RAM)
    t0 = time.time()
    for layer, prefix in enumerate(prefixes):
        for e in range(E):
            gu, dn = ck.expert(prefix, e)
            gu, dn = gu.to(device, dtype), dn.to(device, dtype)
            for s in los.values():
                s.put(layer, e, E, gu, dn)
            bank.hi[(layer, e)] = (gu, dn)
        print(f"[load] layer {layer + 1}/{L}  ({time.time() - t0:.0f}s, CPU RAM used {ram_gb():.1f} GB)", flush=True)
    for s in los.values():
        s.finalize()
    if device == "cuda":
        print(f"[load] GPU memory in use: {torch.cuda.memory_allocated() / 2**30:.2f} GiB", flush=True)

    first_dev = next(model.parameters()).device
    seqs, refs = {}, {}
    usage_check = []
    t0 = time.time()
    todo = [(u, i) for u in names for i in split[u][1]]
    for n, (u, i) in enumerate(todo):
        text = rows[i][1]
        ids = tok.apply_chat_template([{"role": "user", "content": text}], add_generation_prompt=True,
                                      return_tensors="pt", return_dict=True)["input_ids"]
        ids = ids[:, -args.max_prompt_tokens:].to(first_dev)
        skip = min(template_prefix_len(tok, text), ids.shape[1] - 1)
        prompt_len = ids.shape[1]
        with torch.no_grad():
            full = greedy(model, ids, args.gen_tokens, tok.eos_token_id)
            bank.usage[:] = 0
            logits = model(full).logits[0, skip - 1:-1]
        logp = torch.log_softmax(logits.float(), -1)
        top = logp.topk(args.ref_topk, dim=-1)
        reply = torch.zeros(logits.shape[0], dtype=torch.bool)
        reply[max(0, prompt_len - skip):] = True
        seqs[i] = (full.cpu(), skip)
        refs[i] = {"idx": top.indices.to(torch.int32).cpu(), "logp": top.values.half().cpu(), "reply": reply}
        usage_check.append((bank.usage.copy(), counts[i]))
        if n == 0:
            print("[ref] sample reply:", repr(tok.decode(full[0, prompt_len:], skip_special_tokens=True)[:200]), flush=True)
        if (n + 1) % 20 == 0 or n + 1 == len(todo):
            print(f"[ref] {n + 1}/{len(todo)} sequences ({time.time() - t0:.0f}s)", flush=True)

    # sanity: routing in this run must look like the routing recorded by profile_experts.py
    a = np.stack([x for x, _ in usage_check]).sum(0).ravel()
    b = np.stack([y for _, y in usage_check]).sum(0).ravel()
    routing_corr = float(np.corrcoef(a, b)[0, 1])
    print(f"[check] routing correlation with the profiling run: {routing_corr:.3f} (should be > 0.9)", flush=True)

    def evaluate(users):
        out = {}
        for u in users:
            kls, ags, kls_r, ags_r = [], [], [], []
            for i in split[u][1]:
                full, skip = seqs[i]
                with torch.no_grad():
                    logits = model(full.to(first_dev)).logits[0, skip - 1:-1]
                kl, ag = kl_metrics(logits, refs[i])
                r = refs[i]["reply"].numpy()
                kls.append(kl); ags.append(ag); kls_r.append(kl[r]); ags_r.append(ag[r])
            cat = lambda xs: np.concatenate(xs) if xs else np.zeros(0)
            out[u] = {"kl": float(cat(kls).mean()), "top1": float(cat(ags).mean()),
                      "kl_reply": float(cat(kls_r).mean()) if cat(kls_r).size else float("nan"),
                      "top1_reply": float(cat(ags_r).mean()) if cat(ags_r).size else float("nan")}
        return out

    results = {}

    # baselines that need every expert: quantize the full weights in place, reload originals in between
    def reload_full():
        for layer, prefix in enumerate(prefixes):
            for e in range(E):
                gu, dn = ck.expert(prefix, e)
                bank.hi[(layer, e)] = (gu.to(device, dtype), dn.to(device, dtype))

    base_bits = [args.hi_bits] + [u for u in uniform_bits if u not in (args.hi_bits, args.lo_bits)]
    base_bits = [b for b in base_bits if b < 16]
    for n_b, b in enumerate(base_bits):
        if n_b > 0:
            t0 = time.time()
            reload_full()
            print(f"[eval] reloaded full weights ({time.time() - t0:.0f}s)", flush=True)
        for key, (gu, dn) in bank.hi.items():
            bank.hi[key] = (fake_quant(gu, b, args.group), fake_quant(dn, b, args.group))
        results[f"all {b}-bit"] = evaluate(names)
        print(f"[eval] all {b}-bit done ({time.time() - t_start:.0f}s)", flush=True)

    # --- phase 2: drop the full model's experts, keep only codes + current hi set
    bank.hi.clear()
    if device == "cuda":
        torch.cuda.empty_cache()
    bank.lo = los[args.lo_bits].to(device)
    results[f"all {args.lo_bits}-bit"] = evaluate(names)
    print(f"[eval] all {args.lo_bits}-bit done ({time.time() - t_start:.0f}s)", flush=True)
    if device == "cuda":
        print(f"[phase 2] GPU memory: {torch.cuda.memory_allocated() / 2**30:.2f} GiB", flush=True)

    loads = [0, 0.0]

    def set_hi(sets):
        want = {(l, int(e)) for l, ids in enumerate(sets) for e in ids}
        for key in list(bank.hi):
            if key not in want:
                del bank.hi[key]
        t = time.time()
        for (l, e) in want:
            if (l, e) not in bank.hi:
                gu, dn = ck.expert(prefixes[l], e)
                gu, dn = gu.to(device, dtype), dn.to(device, dtype)
                bank.hi[(l, e)] = (fake_quant(gu, args.hi_bits, args.group), fake_quant(dn, args.hi_bits, args.group))
                loads[0] += 1
        loads[1] += time.time() - t

    def ranking(u, rule):
        if rule == "personal":
            score = train_sum[u]
        elif rule == "population":
            score = all_norm - train_norm[u]
        elif rule == "oracle":
            score = test_sum[u]
        elif rule == "random":
            score = np.random.default_rng(zlib.crc32(u.encode())).random((L, E))
        else:
            raise SystemExit(f"unknown rule {rule}")
        noise = np.random.default_rng(1).random((L, E)) * 1e-9
        return np.argsort(-(score + noise), axis=1)

    for b in sorted(budgets, reverse=True):
        for rule in rules:
            results[f"{rule}@{b}"] = {}
    for n, u in enumerate(names):
        for rule in rules:                               # smaller budgets reuse the larger set: no reloads
            order_u = ranking(u, rule)
            for b in sorted(budgets, reverse=True):
                k = max(1, round(E * b))
                set_hi(order_u[:, :k])
                results[f"{rule}@{b}"].update(evaluate([u]))
        print(f"[eval] user {n + 1}/{len(names)}  ({time.time() - t_start:.0f}s, {loads[0]} expert loads in {loads[1]:.0f}s)",
              flush=True)

    # --- report
    def bits_per_weight(b):
        return (b + 32 / args.group) if b < 16 else 16

    def ms(key, metric):
        v = np.array([results[key][u][metric] for u in names], dtype=float)
        return v.mean(), (v.std(ddof=1) / np.sqrt(len(v)) if len(v) > 1 else 0.0)

    lines = [f"model: {args.model}   users: {len(names)}   test sequences: {len(todo)}",
             f"hi = {args.hi_bits}-bit, lo = {args.lo_bits}-bit, group {args.group}, reply tokens: {args.gen_tokens}",
             f"routing check (should be > 0.9): {routing_corr:.3f}", "",
             "KL(full fp16 || quantized) per token, mean over users ± standard error (lower is better)",
             f"{'config':<22} {'bits/weight':>11} {'KL all':>16} {'KL reply':>16} {'top-1 reply':>12}"]
    lines.append("-" * len(lines[-1]))
    order = [f"all {args.hi_bits}-bit"] + [f"all {b}-bit" for b in uniform_bits if b != args.hi_bits]
    if f"all {args.lo_bits}-bit" not in order:
        order.append(f"all {args.lo_bits}-bit")
    for b in sorted(budgets):
        order += [f"{r}@{b}" for r in rules]
    for key in order:
        if key.startswith("all "):
            bpw = bits_per_weight(int(key.split()[1].split("-")[0]))
        else:
            share = float(key.split("@")[1])
            bpw = share * bits_per_weight(args.hi_bits) + (1 - share) * bits_per_weight(args.lo_bits)
        m1, s1 = ms(key, "kl")
        m2, s2 = ms(key, "kl_reply")
        m3, _ = ms(key, "top1_reply")
        lines.append(f"{key:<22} {bpw:>11.2f} {m1:>9.5f} ±{s1:.5f} {m2:>9.5f} ±{s2:.5f} {m3:>11.1%}")

    lo_key = f"all {args.lo_bits}-bit"
    lines += ["", "share of the lo-bit quality loss removed (by KL on reply tokens), and head-to-head wins"]
    for b in sorted(budgets):
        for rule in rules:
            key = f"{rule}@{b}"
            rec = [(results[lo_key][u]["kl_reply"] - results[key][u]["kl_reply"]) /
                   max(results[lo_key][u]["kl_reply"] - results[f"all {args.hi_bits}-bit"][u]["kl_reply"], 1e-9)
                   for u in names]
            line = f"  {key:<20} removes {np.mean(rec):6.1%} of the loss"
            if rule != "personal" and f"personal@{b}" in results:
                wins = sum(results[f"personal@{b}"][u]["kl_reply"] < results[key][u]["kl_reply"] for u in names)
                line += f"   personal better for {wins}/{len(names)} users"
            lines.append(line)
    for b in sorted(budgets):
        for ub in uniform_bits:
            pk, uk = f"personal@{b}", f"all {ub}-bit"
            if pk in results and uk in results:
                wins = sum(results[pk][u]["kl_reply"] < results[uk][u]["kl_reply"] for u in names)
                bp = b * bits_per_weight(args.hi_bits) + (1 - b) * bits_per_weight(args.lo_bits)
                lines.append(f"  personal@{b} ({bp:.2f} bits) vs uniform {ub}-bit ({bits_per_weight(ub):.2f} bits): "
                             f"personal better for {wins}/{len(names)} users")
    lines.append(f"\ntime: {time.time() - t_start:.0f}s, expert loads in phase 2: {loads[0]} ({loads[1]:.0f}s)")
    text = "\n".join(lines)
    print("\n" + text)
    with open(os.path.join(args.outdir, "quant_summary.txt"), "w", encoding="utf-8") as f:
        f.write(text + "\n")
    with open(os.path.join(args.outdir, "quant_summary.json"), "w", encoding="utf-8") as f:
        json.dump({"args": vars(args), "routing_corr": routing_corr, "results": results}, f, indent=1)
    print(f"[saved] {args.outdir}/quant_summary.txt")


